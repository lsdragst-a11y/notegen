def _t2s(s: str) -> str:
    """逐字繁→简归一化；表外字符原样保留。"""
    if not s:
        return s
    return "".join(_T2S.get(ch, ch) for ch in s)


def build_vocab(chunks: list[dict]) -> dict:
    """返回 {"cjk": set[str], "en": set[str]}。cjk 是 jieba 名词短语，en 是标识符/命令。

    除单词外，还将 ocr_text 按行拆分、对每行做连续名词 bigram/trigram 拼接，
    捕获"数据 链路层"→"数据链路层"这类跨 token 的多字术语。
    """
    import jieba.posseg as pseg
    cjk: set[str] = set()
    en: set[str] = set()
    for c in chunks:
        text = c.get("ocr_text") or ""
        if not text:
            continue
        for m in _EN_TERM_RE.findall(text):
            if len(m) >= 2 and m.isascii():
                en.add(m)
        # 按行处理：单词 + 连续名词 bigram/trigram
        for line in text.splitlines():
            line = line.strip()
            if not line:
                continue
            pairs = [(w, flag) for w, flag in pseg.cut(line)]
            noun_flags = {"n", "nr", "ns", "nt", "nz", "vn"}
            buf: list[str] = []
            for w, flag in pairs:
                if not w.isascii() and (flag.startswith("n") or flag in noun_flags):
                    if len(w) >= 2:
                        cjk.add(w)
                    buf.append(w)
                else:
                    buf = []
                # bigram
                if len(buf) >= 2:
                    compound = "".join(buf[-2:])
                    if len(compound) >= 3:
                        cjk.add(compound)
                # trigram
                if len(buf) >= 3:
                    compound = "".join(buf[-3:])
                    if len(compound) >= 4:
                        cjk.add(compound)
    return {"cjk": cjk, "en": en}


def correct_token(tok: str, vocab: dict) -> str | None:
    """tok 的安全面校正：英文走"屏上唯一近似"模糊匹配；CJK 只做繁→简归一化。

    返回校正词，无校正返回 None（不改）。CJK 词表模糊替换已下线（见模块 docstring）。
    """
    if not tok or len(tok) < 2:
        return None
    if tok.isascii():
        # 英文：完全相同跳过；否则找同长度、ratio≥0.8 的唯一候选
        if tok in vocab["en"]:
            return None
        cands = [v for v in vocab["en"]
                 if v.lower() != tok.lower()
                 and abs(len(v) - len(tok)) <= 1
                 and SequenceMatcher(None, tok.lower(), v.lower()).ratio() >= 0.8]
        return cands[0] if len(cands) == 1 else None
    # CJK：只做零歧义繁→简归一化，不再做基于词表的同长模糊替换
    s = _t2s(tok)
    return s if s != tok else None


def correct_headline_and_keywords(chunks: list[dict], vocab: dict) -> int:
    """就地校正每个 chunk 的 headline + keywords。返回校正次数。"""
    if not (vocab.get("cjk") or vocab.get("en")):
        return 0
    import jieba
    n_fix = 0
    for c in chunks:
        hl = c.get("headline") or ""
        if hl:
            # 整串繁→简归一化（字级、上下文无关，无需分词）
            new_hl = _t2s(hl)
            if new_hl != hl:
                n_fix += 1
            # 英文命令名/标识符模糊校正（仅 ascii token，CJK 已由上一步处理）
            for tok in sorted({t for t in jieba.cut(new_hl) if t.isascii()}):
                fixed = correct_token(tok, vocab)
                if fixed:
                    new_hl = new_hl.replace(tok, fixed)
                    n_fix += 1
            c["headline"] = new_hl
        kws = c.get("keywords") or []
        if kws:
            new_kws = []
            for k in kws:
                fixed = correct_token(str(k), vocab)
                new_kws.append(fixed if fixed else k)
                if fixed:
                    n_fix += 1
            c["keywords"] = new_kws
    return n_fix
